
import pymysql

import demo
from conftest import ROOT, run_sql_file


def test_to_inet6_maps_ipv4_and_keeps_ipv6():
    assert demo.to_inet6("10.0.0.2") == "::ffff:10.0.0.2"
    assert demo.to_inet6("2001:db8::1") == "2001:db8::1"


def test_returning_gives_back_id_and_timestamp(cur):
    cur.execute(demo.INSERT_LINK_MODERN, ("https://example.com",))
    link_id, created_at = cur.fetchone()
    assert len(link_id) == 36          # a UUID, generated by the server
    assert created_at is not None      # a default value, handed back in the same statement


def test_inet6_sorts_numerically_but_varchar_sorts_as_text(cur):
    cur.execute(demo.INSERT_LINK_MODERN, ("https://example.com",))
    modern_id = cur.fetchone()[0]
    legacy_id = "00000000-0000-0000-0000-000000000001"
    cur.execute(demo.INSERT_LINK_LEGACY, (legacy_id, "https://example.com"))
    for ip in ("10.0.0.2", "10.0.0.10", "10.0.0.9"):
        cur.execute(demo.INSERT_CLICK_MODERN, (modern_id, demo.to_inet6(ip)))
        cur.execute(demo.INSERT_CLICK_LEGACY, (legacy_id, ip))

    cur.execute("SELECT client_ip FROM clicks ORDER BY client_ip")
    assert [r[0] for r in cur.fetchall()] == ["::ffff:10.0.0.2", "::ffff:10.0.0.9", "::ffff:10.0.0.10"]
    cur.execute("SELECT client_ip FROM clicks_legacy ORDER BY client_ip")
    assert [r[0] for r in cur.fetchall()] == ["10.0.0.10", "10.0.0.2", "10.0.0.9"]  # text order: wrong


def test_inet6_plain_ipv4_is_rejected_or_stored_mapped(cur):
    # MariaDB 10.11 rejects plain IPv4 text in an INET6 column; 13.0.2 accepts it.
    # Either is fine, as long as an accepted value is stored as the IPv4-mapped address.
    cur.execute(demo.INSERT_LINK_MODERN, ("https://example.com",))
    link_id = cur.fetchone()[0]
    try:
        cur.execute(demo.INSERT_CLICK_MODERN, (link_id, "10.0.0.2"))
    except pymysql.MySQLError:
        return
    cur.execute("SELECT client_ip FROM clicks WHERE link_id = %s", (link_id,))
    assert cur.fetchone()[0] == "::ffff:10.0.0.2"


def test_create_or_replace_schema_can_be_run_twice(conn):
    cur = conn.cursor()
    run_sql_file(cur, ROOT / "sql" / "01_modern.sql")
    run_sql_file(cur, ROOT / "sql" / "01_modern.sql")   # no DROP needed, no error
    cur.execute("SELECT COUNT(*) FROM links")
    assert cur.fetchone()[0] == 0
